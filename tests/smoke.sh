#!/usr/bin/env bash
# Live smoke test for the omatray widget and keybind helpers. Run it inside the
# Omarchy session with the plugin installed (./install.sh). It starts from an
# empty dock, opens two throwaway web apps (example.com and example.org), and
# drives them the way the keys do: focus the window, then run the helper. It
# backs up and restores the real dock file and closes the windows it opened,
# whatever happens.
#
# OMATRAY_BIN: helper directory (default: bin/ of this checkout).
# SMOKE_CLASS_PREFIX: window class prefix of the default browser's app windows
# (chrome for Chrome/Chromium; the dock helper only supports chrome-*).
set -euo pipefail

DOCK="${XDG_CONFIG_HOME:-$HOME/.config}/omarchy/omatray.json"
PREFIX="${SMOKE_CLASS_PREFIX:-chrome}"
HIDE_WS="special:omatray"
TIMEOUT="${SMOKE_TIMEOUT:-30}"
REPO="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
OMATRAY_BIN="${OMATRAY_BIN:-$REPO/bin}"

# url|class -- omarchy-launch-webapp produces <prefix>-<host>__<path>-<profile>
# for a URL; with no path that is "<host>__" and the default profile. The dock
# ids are generated by omatray-dock (read from the dock file once docked).
APP_A=("https://example.com" "$PREFIX-example.com__-Default")
APP_B=("https://example.org" "$PREFIX-example.org__-Default")
ID_A="" ID_B=""

WORK="$(mktemp -d)"
HAD_DOCK=0
FAILED=0

log()  { printf '==> %s\n' "$*"; }
fail() { printf 'FAIL: %s\n' "$*" >&2; FAILED=1; exit 1; }
pass() { printf '  ok: %s\n' "$*"; }

# ---- hyprland queries (everything goes through jq on `hyprctl clients -j`) ----
addr_of()   { hyprctl clients -j | jq -r --arg c "$1" \
                '[.[] | select((.class | ascii_downcase) == ($c | ascii_downcase))][0].address // empty'; }
ws_of()     { hyprctl clients -j | jq -r --arg a "$1" \
                '[.[] | select(.address == $a)][0].workspace.name // empty'; }
active_ws() { hyprctl activeworkspace -j | jq -r '.id'; }
focused()   { hyprctl activewindow -j | jq -r '.address // empty'; }
omatray()   { omarchy-shell omatray "$@"; }

# wait_until <description> <command...>: poll until the command succeeds.
wait_until() {
  local what="$1" i; shift
  for ((i = 0; i < TIMEOUT * 4; i++)); do
    if "$@"; then pass "$what"; return 0; fi
    sleep 0.25
  done
  fail "timed out waiting for: $what"
}

has_window()    { [[ -n "$(addr_of "$1")" ]]; }
no_window()     { [[ -z "$(addr_of "$1")" ]]; }
on_ws()         { [[ "$(ws_of "$(addr_of "$1")")" == "$2" ]]; }
on_active_ws()  { [[ "$(ws_of "$(addr_of "$1")")" == "$(hyprctl activeworkspace -j | jq -r '.name')" ]]; }
is_focused()    { local a; a="$(addr_of "$1")"; [[ -n "$a" && "$(focused)" == "$a" ]]; }

assert_ws_unchanged() {
  [[ "$(active_ws)" == "$1" ]] || fail "active workspace changed ($1 -> $(active_ws)) $2"
}

# ---- setup / teardown ----
write_empty_dock() {
  mkdir -p "$(dirname "$DOCK")"
  # temp file + rename, the way the real helpers write it: exercises the
  # watcher surviving an inode change.
  printf '{"apps": []}\n' > "$DOCK.smoke-tmp"
  mv "$DOCK.smoke-tmp" "$DOCK"
}

# The dock id for a window class, read from the dock file (empty if absent).
id_for_class() {
  jq -r --arg c "$1" '[.apps[]? | select((.matchClass | ascii_downcase) == ($c | ascii_downcase))][0].id // empty' \
    "$DOCK" 2>/dev/null || true
}
in_dock()  { [[ -n "$(id_for_class "$1")" ]]; }
not_in_dock() { [[ -z "$(id_for_class "$1")" ]]; }

# Focus a window by class, like clicking it. Only for windows on the active
# workspace (focusing a hidden one would switch workspaces).
focus_class() {
  local a; a="$(addr_of "$1")"
  [[ "$a" =~ ^0x[0-9a-fA-F]+$ ]] || fail "no window to focus for $1"
  hyprctl dispatch "hl.dsp.focus({ window = \"address:$a\" })" >/dev/null
  wait_until "$1 focused" is_focused "$1"
}

close_by_class() {
  local a; a="$(addr_of "$1")"
  # hl.dsp.window.close falls back to the ACTIVE window when handed an empty
  # address, so never call it without one.
  [[ "$a" =~ ^0x[0-9a-fA-F]+$ ]] || return 0
  hyprctl dispatch "hl.dsp.window.close({ window = \"address:$a\" })" >/dev/null || true
}

cleanup() {
  local rc=$?
  set +e
  log "Cleaning up"
  close_by_class "${APP_A[1]}"
  close_by_class "${APP_B[1]}"
  if ((HAD_DOCK)); then cp -f "$WORK/omatray.json.bak" "$DOCK"; else rm -f "$DOCK"; fi
  rm -f "$DOCK.smoke-tmp"
  rm -rf "$WORK"
  if ((rc == 0 && FAILED == 0)); then log "PASS"; else log "FAILED (exit $rc)"; fi
}
trap cleanup EXIT

preflight() {
  for c in hyprctl jq omarchy-shell omarchy-launch-webapp; do
    command -v "$c" >/dev/null || fail "missing command: $c"
  done
  has_window "${APP_A[1]}" && fail "a window of class ${APP_A[1]} is already open; close it first"
  has_window "${APP_B[1]}" && fail "a window of class ${APP_B[1]} is already open; close it first"
  for c in omatray-dock omatray-close omatray-undock; do
    [[ -x "$OMATRAY_BIN/$c" ]] || fail "missing helper: $OMATRAY_BIN/$c"
  done
  if [[ -e "$DOCK" ]]; then cp -p "$DOCK" "$WORK/omatray.json.bak"; HAD_DOCK=1; fi
  return 0
}

# ---- steps ----
step_launch() {
  log "Start from an empty dock; launch both apps directly (not docked yet)"
  write_empty_dock
  sleep 3 # watcher + one poll tick: the widget must see the empty dock
  omarchy-launch-webapp "${APP_A[0]}" >/dev/null 2>&1 &
  wait_until "A window exists" has_window "${APP_A[1]}"
  omarchy-launch-webapp "${APP_B[0]}" >/dev/null 2>&1 &
  wait_until "B window exists" has_window "${APP_B[1]}"
  sleep 2
}

step_dock() {
  log "SUPER+M: dock A and B (each is minimized to $HIDE_WS)"
  focus_class "${APP_A[1]}"
  "$OMATRAY_BIN/omatray-dock"
  wait_until "A in the dock file" in_dock "${APP_A[1]}"
  wait_until "A on $HIDE_WS" on_ws "${APP_A[1]}" "$HIDE_WS"
  ID_A="$(id_for_class "${APP_A[1]}")"
  pass "A docked as $ID_A"
  sleep 1
  focus_class "${APP_B[1]}"
  "$OMATRAY_BIN/omatray-dock"
  wait_until "B in the dock file" in_dock "${APP_B[1]}"
  wait_until "B on $HIDE_WS" on_ws "${APP_B[1]}" "$HIDE_WS"
  ID_B="$(id_for_class "${APP_B[1]}")"
  pass "B docked as $ID_B"
  [[ "$ID_A" != "$ID_B" ]] || fail "A and B got the same id"
  sleep 3 # the widget must pick up both entries and windows before IPC
}

step_show() {
  log "Show A: only A comes back"
  local ws; ws="$(active_ws)"
  omatray show "$ID_A"
  wait_until "A on the active workspace" on_active_ws "${APP_A[1]}"
  wait_until "A focused" is_focused "${APP_A[1]}"
  on_ws "${APP_B[1]}" "$HIDE_WS" || fail "B left $HIDE_WS"
  pass "B still on $HIDE_WS"
  assert_ws_unchanged "$ws" "after show"
  pass "active workspace unchanged"
  sleep 1
}

step_close_minimizes() {
  log "SUPER+W on docked A: minimize, still running"
  focus_class "${APP_A[1]}"
  "$OMATRAY_BIN/omatray-close"
  wait_until "A on $HIDE_WS" on_ws "${APP_A[1]}" "$HIDE_WS"
  has_window "${APP_A[1]}" || fail "A was closed"
  pass "A still running"
  sleep 1
}

step_force_close() {
  log "SUPER+ALT+W on docked A: really closed, stays docked"
  omatray show "$ID_A"
  wait_until "A on the active workspace" on_active_ws "${APP_A[1]}"
  focus_class "${APP_A[1]}"
  "$OMATRAY_BIN/omatray-close" --force
  wait_until "A window gone" no_window "${APP_A[1]}"
  in_dock "${APP_A[1]}" || fail "A was removed from the dock file"
  pass "A still in the dock file"
  has_window "${APP_B[1]}" || fail "closing A also closed B"
  pass "B untouched"
  sleep 2
}

step_relaunch() {
  log "Toggle on the not-running A relaunches it"
  omatray toggle "$ID_A"
  wait_until "A window exists" has_window "${APP_A[1]}"
  wait_until "A on the active workspace" on_active_ws "${APP_A[1]}"
  sleep 2
}

step_undock() {
  log "SUPER+ALT+M: undock A, window stays open where it is"
  focus_class "${APP_A[1]}"
  local ws; ws="$(ws_of "$(addr_of "${APP_A[1]}")")"
  "$OMATRAY_BIN/omatray-undock"
  wait_until "A gone from the dock file" not_in_dock "${APP_A[1]}"
  has_window "${APP_A[1]}" || fail "undock closed A"
  on_ws "${APP_A[1]}" "$ws" || fail "undock moved A off workspace $ws"
  pass "A window untouched on workspace $ws"
  in_dock "${APP_B[1]}" || fail "undocking A removed B"
  pass "B still docked"
}

preflight
step_launch
step_dock
step_show
step_close_minimizes
step_force_close
step_relaunch
step_undock
